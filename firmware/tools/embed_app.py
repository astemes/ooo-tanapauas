#!/usr/bin/env python3
"""Compile the companion app into the firmware.

Reads app/dist (index.html, manifest.webmanifest, icon.png) and writes
firmware/src/net/app_bundle.h with gzipped byte arrays. Without a built app
it embeds tools/placeholder.html so the box still serves something useful.

Usage: python3 firmware/tools/embed_app.py
"""
import gzip
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
DIST = ROOT / "app" / "dist"
OUT = ROOT / "firmware" / "src" / "net" / "app_bundle.h"
PLACEHOLDER = pathlib.Path(__file__).with_name("placeholder.html")

FILES = [  # (url path, file name, content type, gzip?)
    ("/", "index.html", "text/html; charset=utf-8", True),
    ("/manifest.webmanifest", "manifest.webmanifest", "application/manifest+json", True),
    ("/icon.png", "icon.png", "image/png", False),
]


def c_array(name: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i : i + 16]) for i in range(0, len(data), 16)]
    return f"const uint8_t {name}[] = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def main() -> None:
    entries, arrays = [], []
    built = (DIST / "index.html").exists()
    for i, (url, fname, ctype, gz) in enumerate(FILES):
        src = DIST / fname if built else (PLACEHOLDER if fname == "index.html" else None)
        if src is None or not src.exists():
            continue
        data = src.read_bytes()
        if gz:
            data = gzip.compress(data, compresslevel=9, mtime=0)
        arrays.append(c_array(f"kFile{i}", data))
        entries.append(f'  {{"{url}", "{ctype}", kFile{i}, sizeof kFile{i}, {"true" if gz else "false"}}},')
    total = sum(len(a) for a in arrays)
    OUT.write_text(
        "// Generated by firmware/tools/embed_app.py. Do not edit.\n"
        f"// Source: {'app/dist' if built else 'firmware/tools/placeholder.html'}\n"
        "#pragma once\n#include <cstddef>\n#include <cstdint>\n\nnamespace app_bundle {\n\n"
        "struct File {\n  const char* path;\n  const char* type;\n  const uint8_t* data;\n  size_t len;\n  bool gzip;\n};\n\n"
        + "".join(arrays)
        + "\nconst File kFiles[] = {\n"
        + "\n".join(entries)
        + "\n};\n\n}  // namespace app_bundle\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)} from {'app/dist' if built else 'placeholder'}; "
          f"{len(entries)} files, ~{total // 6} bytes")


if __name__ == "__main__":
    main()
