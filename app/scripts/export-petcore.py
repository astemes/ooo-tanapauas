#!/usr/bin/env python3
"""Export pet sprites and tuning constants from lib/petcore into app/src/generated/petcore.json.

Parses lib/petcore/src/sprites.cpp (Art/Face/Feature string arrays, kClosedEyes,
kFaceAt, kFeatureY, kSpeciesFeature, kHeart, kBodyColour, palette colours), the
species table in species.cpp and the tuning constants in tuning.h, so the app draws
exactly the same pixels as the box. Run: python3 app/scripts/export-petcore.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "lib" / "petcore" / "src"
OUT = ROOT / "app" / "src" / "generated" / "petcore.json"


def strings(block):
    return re.findall(r'"([^"]*)"', block)


def array(src, pattern):
    m = re.search(pattern + r"\s*=\s*\{(.*?)\};", src, re.S)
    if not m:
        sys.exit(f"export-petcore: cannot find {pattern!r}")
    return m.group(1)


def main():
    sprites = (SRC / "sprites.cpp").read_text()
    species_cpp = (SRC / "species.cpp").read_text()
    tuning_h = (SRC / "tuning.h").read_text()

    art = {name: strings(body) for name, body in re.findall(r"Art\s+(k\w+)\s*=\s*\{(.*?)\};", sprites, re.S)}
    faces = {name: strings(body) for name, body in re.findall(r"Face\s+(k\w+)\s*=\s*\{(.*?)\};", sprites, re.S)}
    closed = re.search(r'kClosedEyes\s*=\s*"([^"]*)"', sprites).group(1)
    face_at = [[int(x), int(y)] for x, y in re.findall(r"\{\s*(-?\d+)\s*,\s*(-?\d+)\s*\}", array(sprites, r"kFaceAt\[\]"))]
    heart = strings(array(sprites, r"kHeart\[kHeartSize\]"))
    features = {name: strings(body) for name, body in re.findall(r"Feature\s+(k\w+)\s*=\s*\{(.*?)\};", sprites, re.S)}
    feature_y = [int(v) for v in re.findall(r"-?\d+", array(sprites, r"kFeatureY\[\]"))]
    feature_of = re.findall(r"nullptr|k\w+", array(sprites, r"kSpeciesFeature\[\]"))
    rarities = ["Common", "Uncommon", "Rare", "Legendary"]
    eggs = [
        {"minutes": int(m), "weight": [int(w) for w in ws.split(",")]}
        for m, ws in re.findall(r"\{(\d+),\s*\{([\d,\s]+)\}\}", array(tuning_h, r"kEggs\[\]"))
    ]
    if not eggs:
        sys.exit("export-petcore: no kEggs")
    table = re.findall(r'\{"(\w+)",\s*Rarity::(\w+),\s*0x([0-9A-Fa-f]{6}),\s*0x([0-9A-Fa-f]{6})\}', species_cpp)
    if len(table) != len(feature_of):
        sys.exit(f"export-petcore: {len(table)} species but {len(feature_of)} features")
    species = [
        {
            "name": name,
            "rarity": rarity,
            "body": None if body == "000000" else body.upper(),
            "accent": accent.upper(),
            "feature": None if feat == "nullptr" else features[feat],
        }
        for (name, rarity, body, accent), feat in zip(table, feature_of)
    ]
    body_colour = re.findall(r"0x([0-9A-Fa-f]{6})", array(sprites, r"kBodyColour\[\]"))

    # Fixed palette entries from palette_rgb(): `case kOutline: return 0x2B2233;`
    palette = {k: v.upper() for k, v in re.findall(r"case\s+k(\w+):\s*return\s+0x([0-9A-Fa-f]{6});", sprites)}
    egg = dict(re.findall(r"case\s+k(\w+):\s*return\s+stage\s*==\s*Stage::Egg\s*\?\s*0x([0-9A-Fa-f]{6})", sprites))

    stages = ["Egg", "Baby", "Child", "Teen", "Adult", "Elder"]
    tuning = {name: int(val) for name, val in re.findall(r"constexpr\s+\w+\s+(k\w+)\s*=\s*(\d+)\s*;", tuning_h)}
    stage_xp = [int(v) for v in re.findall(r"\d+", array(tuning_h, r"kStageXp\[\]"))]

    for need in ("kEgg", "kTombstone", *("k" + s for s in stages[1:])):
        if need not in art:
            sys.exit(f"export-petcore: missing art {need}")
    out = {
        "_source": "generated by app/scripts/export-petcore.py from lib/petcore; do not edit",
        "size": 16,
        "stages": stages,
        "moods": ["Happy", "Content", "Sad", "Crying", "Dead", "Sleeping"],
        "bodies": [art["k" + s] for s in stages],
        "tombstone": art["kTombstone"],
        "faces": [faces["kFace" + m] for m in ("Happy", "Content", "Sad", "Crying", "Sleeping")],
        "closedEyes": closed,
        "faceAt": face_at,
        "heart": heart,
        "featureY": feature_y,
        "species": species,
        "rarities": rarities,
        "eggs": eggs,
        "bodyColour": [c.upper() for c in body_colour],
        "palette": {
            "outline": palette["Outline"],
            "white": palette["White"],
            "cheek": palette["Cheek"],
            "tear": palette["Tear"],
            "heartFull": palette["HeartFull"],
            "heartEmpty": palette["HeartEmpty"],
            "eggShade": egg["Shade"].upper(),
            "eggAccent": egg["Accent"].upper(),
        },
        "tuning": {**tuning, "kStageXp": stage_xp},
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(out, indent=1) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
